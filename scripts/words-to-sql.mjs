// Writes supabase/migrations/20261113000200_words_seed.sql from src/data/words.json:
// the deck the app ships with, loaded into an empty database.
// Usage: node scripts/words-to-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'supabase/migrations/20261113000200_words_seed.sql';
const topics = JSON.parse(readFileSync('src/data/words.json', 'utf8'));

const q = (s) => (s == null ? 'null' : `'${String(s).replaceAll("'", "''")}'`);

const singles = [];
const forms = [];
const plurals = [];
topics.forEach((t) => {
  t.words.forEach(([mt, pl, en, extra], i) => {
    singles.push(`  (${q(t.topic)}, ${q(mt)}, ${q(pl)}, ${q(en)}, ${i * 10})`);
    if (typeof extra === 'string') forms.push(`  (${q(mt)}, ${q(extra)})`);
    if (Array.isArray(extra)) {
      const [pmt, ppl, pen] = extra;
      plurals.push(`  (${q(t.topic)}, ${q(pmt)}, ${q(ppl)}, ${q(pen)}, ${i * 10 + 1}, ${q(mt)})`);
    }
  });
});

const sql = `-- The deck the app ships with (generated by scripts/words-to-sql.mjs from src/data/words.json).
-- Run once, after 20261113000100_words.sql, on empty tables.

begin;

insert into public.topics (name, note, position) values
${topics.map((t, i) => `  (${q(t.topic)}, ${q(t.note)}, ${i * 10})`).join(',\n')};

-- Dictionary forms and plain words first, so verb forms and plurals can point at them.
insert into public.words (topic_id, mt, pl, en, position)
select t.id, v.mt, v.pl, v.en, v.position
from (values
${singles.join(',\n')}
) as v (topic, mt, pl, en, position)
join public.topics t on t.name = v.topic;

update public.words w set form_of = v.form_of
from (values
${forms.join(',\n')}
) as v (mt, form_of)
where w.mt = v.mt;

insert into public.words (topic_id, mt, pl, en, position, plural_of)
select t.id, v.mt, v.pl, v.en, v.position, v.plural_of
from (values
${plurals.join(',\n')}
) as v (topic, mt, pl, en, position, plural_of)
join public.topics t on t.name = v.topic;

commit;
`;
writeFileSync(OUT, sql);
console.log(`Wrote ${OUT}: ${topics.length} topics, ${singles.length} words, ${plurals.length} plurals.`);
